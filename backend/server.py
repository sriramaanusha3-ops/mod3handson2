# Simple TF-IDF Vector Space Model Engine for Semantic Retrieval
def tokenize(text):
    return re.findall(r'\w+', text.lower())

def build_corpus_index(docs):
    corpus = [tokenize(d["title"] + " " + d["category"] + " " + d["content"] + " " + " ".join(d["tags"])) for d in docs]
    N = len(corpus)
    df = Counter()
    for doc in corpus:
        unique_words = set(doc)
        for w in unique_words:
            df[w] += 1
    
    idf = {w: math.log((N + 1) / (count + 1)) + 1.0 for w, count in df.items()}
    
    doc_vectors = []
    for doc in corpus:
        tf = Counter(doc)
        total_terms = len(doc)
        vec = {w: (freq / total_terms) * idf.get(w, 1.0) for w, freq in tf.items()}
        # Normalize
        norm = math.sqrt(sum(val ** 2 for val in vec.values())) or 1.0
        norm_vec = {w: val / norm for w, val in vec.items()}
        doc_vectors.append(norm_vec)
        
    return idf, doc_vectors

IDF_DICT, DOC_VECTORS = build_corpus_index(KNOWLEDGE_BASE)

def compute_cosine_similarity(query_text, doc_index):
    query_tokens = tokenize(query_text)
    if not query_tokens:
        return 0.0
    
    tf = Counter(query_tokens)
    total_terms = len(query_tokens)
    q_vec = {w: (freq / total_terms) * IDF_DICT.get(w, 1.0) for w, freq in tf.items()}
    q_norm = math.sqrt(sum(val ** 2 for val in q_vec.values())) or 1.0
    q_norm_vec = {w: val / q_norm for w, val in q_vec.items()}
    
    d_vec = DOC_VECTORS[doc_index]
    
    score = sum(q_norm_vec.get(w, 0.0) * d_vec.get(w, 0.0) for w in q_norm_vec)
    
    # Add a semantic baseline boost if partial token matches exist
    if score == 0.0:
        matches = sum(1 for w in query_tokens if any(w in term for term in d_vec.keys()))
        if matches > 0:
            score = 0.15 + (0.1 * min(matches, 3))
            
    return min(1.0, max(0.0, score))

